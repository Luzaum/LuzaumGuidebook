/**
 * Metadados mínimos para listagens do catálogo público — evita importar diseases.seed/medications.seed (~260 kB gzip) só para montar cartões.
 * Manter em sincronia com `CONSULTA_VET_PUBLIC_*` em `constants/publicCatalog.ts`.
 */
function diseaseListCard(
  partial: Pick<
    DiseaseRecord,
    'id' | 'slug' | 'title' | 'synonyms' | 'species' | 'category' | 'categories' | 'tags' | 'quickSummary'
  >
): DiseaseRecord {
  return {
    ...partial,
    quickDecisionStrip: [],
    etiology: '',
    epidemiology: '',
    pathogenesisTransmission: '',
    pathophysiology: '',
    clinicalSignsPathophysiology: [],
    diagnosis: '',
    treatment: '',
    prevention: '',
    relatedConsensusSlugs: [],
    relatedMedicationSlugs: [],
  };
}

function medicationListCard(
  partial: Pick<
    MedicationRecord,
    | 'id'
    | 'slug'
    | 'title'
    | 'activeIngredient'
    | 'isControlled'
    | 'tradeNames'
    | 'pharmacologicClass'
    | 'species'
    | 'category'
    | 'tags'
    | 'indications'
  >
): MedicationRecord {
  return {
    ...partial,
    mechanismOfAction: '',
    contraindications: [],
    cautions: [],
    adverseEffects: [],
    interactions: [],
    routes: [],
    doses: [],
    presentations: [],
    clinicalNotesRichText: '',
    relatedDiseaseSlugs: [],
  };
}

